"""GI-005: partial-clone fetch and the repository's exclusion policy."""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest

from repo_intel import github
from repo_intel.snapshot import missing_objects, snapshot_commit
from repo_intel.store import ObjectStore

GIT_ENV = {
    "PATH": os.environ.get("PATH", ""), "HOME": os.devnull, "GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": os.devnull,
    "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.test", "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@example.test",
    "GIT_AUTHOR_DATE": "2026-01-01T00:00:00Z", "GIT_COMMITTER_DATE": "2026-01-01T00:00:00Z",
}


def git(repo: Path, *args: str, stdin: bytes | None = None) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], env=GIT_ENV, input=stdin, check=True, capture_output=True).stdout.decode()


@pytest.fixture
def source(tmp_path: Path) -> tuple[Path, str]:
    """A repository with source, vendored and generated code, a binary and a repository policy."""
    repo = tmp_path / "source"
    files = {
        "app/main.py": "print('hello')\n",
        "app/schema_pb2.py": "# generated by protoc\n",
        "node_modules/lib/index.js": "module.exports = 1\n",
        "vendor/ours/patch.py": "# our own fork, kept in vendor/\n",
        "third_party/big.js": "var x = 1;\n",
        "docs/drafts/notes.md": "draft\n",
        "docs/guide.md": "guide\n",
        "logo.png": "\x89PNG not really\n",
        ".gitattributes": "*_pb2.py linguist-generated\nvendor/ours/** -linguist-vendored\nthird_party/** linguist-vendored=true\n",
        ".rkp/exclude": "# drafts are not source\ndocs/drafts/\n",
    }
    for path, text in files.items():
        (repo / path).parent.mkdir(parents=True, exist_ok=True)
        (repo / path).write_text(text)
    git(tmp_path, "init", "-q", "-b", "main", str(repo))
    git(repo, "config", "uploadpack.allowFilter", "true")
    git(repo, "config", "uploadpack.allowAnySHA1InWant", "true")
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "base")
    return repo, git(repo, "rev-parse", "HEAD").strip()


def test_repository_policy_decides_exclusions_with_reasons(tmp_path, source):
    repo, sha = source
    pm = snapshot_commit(ObjectStore(tmp_path / "store", "t"), repo, sha)
    reasons = {x["path"]: (x["reason"], x.get("detail", {}).get("rule")) for x in pm["exclusions"]}
    assert reasons == {
        "app/schema_pb2.py": ("generated", ".gitattributes"),
        "node_modules/lib/index.js": ("vendored_or_generated_dir", None),
        "third_party/big.js": ("vendored", ".gitattributes"),
        "docs/drafts/notes.md": ("repository_policy", ".rkp/exclude"),
        "logo.png": ("binary", None),
    }
    kept = {e["path"] for e in pm["entries"]}
    # -linguist-vendored puts the repository's own code in vendor/ back; the policy files are pinned with the commit.
    assert kept == {"app/main.py", "vendor/ours/patch.py", "docs/guide.md", ".gitattributes", ".rkp/exclude"}
    assert pm["exclusion_policy"].startswith("sha256:")


def test_partial_clone_fetches_only_what_the_snapshot_reads(tmp_path, source):
    repo, sha = source
    mirror = tmp_path / "mirror.git"
    git(tmp_path, "init", "-q", "--bare", str(mirror))
    calls: list[list[str]] = []

    def run(args: list[str], timeout: int, stdin: bytes | None) -> None:
        calls.append(args)
        subprocess.run(["git", "-c", "protocol.file.allow=always", *args], env=GIT_ENV, input=stdin, check=True, capture_output=True, timeout=timeout)

    github.partial_fetch(run, mirror, repo.as_uri(), sha)
    oids = dict(line.split("\t")[::-1] for line in git(repo, "ls-tree", "-r", sha).splitlines() if line)
    oids = {path: meta.split()[2] for path, meta in oids.items()}
    absent = set(missing_objects(mirror, list(oids.values())))
    # Excluded blobs never left the source; everything the snapshot reads did.
    assert {p for p, oid in oids.items() if oid in absent} == {"app/schema_pb2.py", "node_modules/lib/index.js", "third_party/big.js", "docs/drafts/notes.md", "logo.png"}
    # The mirror's snapshot is the source's snapshot, without any network access.
    a = snapshot_commit(ObjectStore(tmp_path / "a", "t"), repo, sha)
    b = snapshot_commit(ObjectStore(tmp_path / "b", "t"), mirror, sha)
    assert a == b
    # A second fetch of the same commit makes no request to the host.
    fetches = sum(1 for c in calls if "fetch" in c)
    github.partial_fetch(run, mirror, repo.as_uri(), sha)
    assert sum(1 for c in calls if "fetch" in c) == fetches


def test_snapshot_never_fetches_a_missing_blob(tmp_path, source):
    """A partial mirror missing a blob the snapshot needs fails instead of reaching the network."""
    repo, sha = source
    mirror = tmp_path / "mirror.git"
    git(tmp_path, "init", "-q", "--bare", str(mirror))
    for key, value in (("core.repositoryformatversion", "1"), ("extensions.partialClone", "origin"), ("remote.origin.url", repo.as_uri()), ("remote.origin.promisor", "true")):
        git(mirror, "config", key, value)
    git(mirror, "-c", "protocol.file.allow=always", "fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", sha)
    with pytest.raises(RuntimeError, match="not in the mirror"):
        snapshot_commit(ObjectStore(tmp_path / "s", "t"), mirror, sha)
