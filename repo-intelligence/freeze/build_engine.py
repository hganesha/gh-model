"""Freeze the `rkp` command line into one folder that needs no Python installed.

    .venv/bin/pip install -e '.[freeze]'
    .venv/bin/python freeze/build_engine.py [--out DIR]

Writes DIR/rkp/ (default: packages/vscode-extension/engine/rkp/), with the
executable `rkp` (`rkp.exe` on Windows) and its libraries beside it. It is built for
the platform it runs on; CI builds one per platform for platform-specific VSIX files.

The frozen engine is its own step worker: the build graph starts it as
`rkp __step_worker__ --inputs ...` inside the same OS sandbox as `python -m
repo_intel.compile.step_worker` (repo_intel.compile.buildgraph.worker_command).

The repo_intel sources are shipped as files beside the bytecode: the step registry is
found by reading them, and package data (catalogues, model pins) is read through
importlib.resources. The server, Temporal and other service-only packages are left out.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DEFAULT_OUT = ROOT.parent / "packages" / "vscode-extension" / "engine"

# Service-only: the API server, workflows and their stacks. The engine never imports them.
EXCLUDE = ["repo_intel.server", "fastapi", "starlette", "uvicorn", "temporalio", "tkinter", "pytest", "hypothesis", "IPython"]

SPEC = """# Generated by freeze/build_engine.py
from PyInstaller.utils.hooks import collect_all, collect_data_files, collect_submodules

datas = collect_data_files("repo_intel", include_py_files=True, excludes=["**/__pycache__", "**/__pycache__/**", "server/**"])
hidden = collect_submodules("repo_intel", filter=lambda name: not name.startswith("repo_intel.server"))
binaries = []
for package in {grammars!r}:
    d, b, h = collect_all(package)
    datas += d; binaries += b; hidden += h
hidden += collect_submodules("sqlglot")

a = Analysis([{entry!r}], pathex=[{root!r}], binaries=binaries, datas=datas, hiddenimports=hidden, excludes={exclude!r}, noarchive=False)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name="rkp", console=True, strip=False, upx=False)
coll = COLLECT(exe, a.binaries, a.datas, name="rkp", strip=False, upx=False)
"""

GRAMMARS = ["tree_sitter", "tree_sitter_python", "tree_sitter_javascript", "tree_sitter_typescript", "hcl2", "lark"]


def flatten_symlinks(root: Path) -> None:
    """Replace symlinks with what they point at: a VSIX is a zip, which cannot carry them.

    Links inside a macOS framework (Python.framework/Python, Versions/Current, Resources)
    are bookkeeping the loader does not use, and are removed rather than copied.
    """
    links = sorted((p for p in root.rglob("*") if p.is_symlink()), key=lambda p: len(p.parts), reverse=True)
    for link in links:
        target = link.resolve()
        link.unlink()
        if any(part.endswith(".framework") for part in link.relative_to(root).parts[:-1]):
            continue
        if not target.is_file() or not target.is_relative_to(root.resolve()):
            raise SystemExit(f"cannot flatten {link} -> {target}")
        shutil.copy2(target, link)


def build(out: Path) -> Path:
    work = Path(tempfile.mkdtemp(prefix="rkp-freeze-"))
    try:
        entry = work / "rkp_entry.py"
        entry.write_text("import sys\nfrom repo_intel.cli import main\nsys.exit(main())\n")
        spec = work / "rkp.spec"
        spec.write_text(SPEC.format(grammars=GRAMMARS, entry=str(entry), root=str(ROOT), exclude=EXCLUDE))
        out.mkdir(parents=True, exist_ok=True)
        shutil.rmtree(out / "rkp", ignore_errors=True)
        subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN", "--distpath", str(out), "--workpath", str(work / "build"), str(spec)], check=True)
    finally:
        shutil.rmtree(work, ignore_errors=True)
    flatten_symlinks(out / "rkp")
    executable = out / "rkp" / ("rkp.exe" if sys.platform == "win32" else "rkp")
    if not executable.is_file():
        raise SystemExit(f"freeze produced no executable at {executable}")
    return executable


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"output folder (default: {DEFAULT_OUT})")
    args = parser.parse_args()
    executable = build(args.out.resolve())
    print(executable)
    return 0


if __name__ == "__main__":
    sys.exit(main())
